CREATE DATABASE IF NOT EXISTS biblioteca CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE biblioteca;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(100) NOT NULL,
 documento VARCHAR(20) NOT NULL UNIQUE, email VARCHAR(120) NOT NULL,
 username VARCHAR(40) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 rol ENUM('ADMIN','EMPLEADO') NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS alumnos (
 id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(100) NOT NULL,
 documento VARCHAR(20) NOT NULL UNIQUE, email VARCHAR(120) NOT NULL,
 grupo VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS libros (
 id INT AUTO_INCREMENT PRIMARY KEY, titulo VARCHAR(150) NOT NULL,
 autor VARCHAR(100) NOT NULL, isbn VARCHAR(30) NOT NULL UNIQUE,
 stock INT NOT NULL CHECK(stock >= 0)
);
CREATE TABLE IF NOT EXISTS prestamos (
 id INT AUTO_INCREMENT PRIMARY KEY, alumno_id INT NOT NULL, libro_id INT NOT NULL,
 usuario_id INT NOT NULL, fecha_prestamo DATE NOT NULL,
 fecha_devolucion DATE NULL, estado ENUM('ACTIVO','DEVUELTO') NOT NULL DEFAULT 'ACTIVO',
 CONSTRAINT fk_prestamo_alumno FOREIGN KEY(alumno_id) REFERENCES alumnos(id),
 CONSTRAINT fk_prestamo_libro FOREIGN KEY(libro_id) REFERENCES libros(id),
 CONSTRAINT fk_prestamo_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id)
);
CREATE INDEX idx_prestamos_estado ON prestamos(estado);
